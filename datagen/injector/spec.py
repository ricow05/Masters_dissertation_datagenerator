"""``ErrorSpec``: everything that defines the errors (an ``error_spec.json``, and ``"error_spec"`` in ``dataset.json``).

It is independent of the clean data's spec. The same clean data can get any number of error
specs, and an error spec can be applied to clean data that was not generated by datagen.
"""
from __future__ import annotations

from dataclasses import dataclass, field

FORMAT_VERSION = 1
MECHANISMS = ("random", "neighbour", "confusion")
ELIGIBLE = ("rule_attributes", "all")


def as_list(values):
    return [values] if isinstance(values, str) else sorted(values)


@dataclass
class RowWeight:
    """Multiply the error weight of the rows of ``table`` that match ``where`` by ``factor``.

    For the child table ``where`` may also name parent attributes (the joined row is used).
    """

    table: str
    where: dict
    factor: float

    def to_dict(self):
        return {"table": self.table, "where": {a: as_list(v) for a, v in self.where.items()}, "factor": self.factor}

    @classmethod
    def from_dict(cls, data):
        return cls(data["table"], dict(data["where"]), float(data["factor"]))


@dataclass
class ErrorSpec:
    """The fields are explained in ``datagen.injector.inject``.

    ``seed`` is the seed of the error stream. With ``None`` (the default) the stream comes
    from the clean data's seed (``datagen.inject``), or must be given (``inject_errors``).
    """

    rate: float = 0.05
    rate_by_table: dict = field(default_factory=dict)
    rate_by_attribute: dict = field(default_factory=dict)
    eligible: str | list = "rule_attributes"
    count: str = "exact"
    row_weights: list = field(default_factory=list)
    mechanism: dict = field(default_factory=lambda: {"random": 1.0})
    confusion: dict = field(default_factory=dict)
    detectable_share: float | None = None
    target_rules: list | None = None
    on_shortfall: str = "skip"
    seed: int | None = None

    def to_dict(self):
        return {
            "format_version": FORMAT_VERSION,
            "rate": self.rate,
            "rate_by_table": dict(self.rate_by_table),
            "rate_by_attribute": dict(self.rate_by_attribute),
            "eligible": self.eligible if isinstance(self.eligible, str) else list(self.eligible),
            "count": self.count,
            "row_weights": [rw.to_dict() for rw in self.row_weights],
            "mechanism": dict(self.mechanism),
            "confusion": self.confusion,
            "detectable_share": self.detectable_share,
            "target_rules": None if self.target_rules is None else list(self.target_rules),
            "on_shortfall": self.on_shortfall,
            "seed": self.seed,
        }

    @classmethod
    def from_dict(cls, data):
        data = dict(data)
        version = data.pop("format_version", FORMAT_VERSION)
        if version != FORMAT_VERSION:
            raise ValueError(f"unsupported error spec format_version {version}")
        data["row_weights"] = [RowWeight.from_dict(rw) for rw in data.get("row_weights", [])]
        return cls(**data)
